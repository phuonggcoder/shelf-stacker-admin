const jsFiles = glob.sync('public/assets/js/**/*.js');
let totalConsoleLogsFixed = 0;

jsFiles.forEach(file => {
    let content = fs.readFileSync(file, 'utf-8');
    const originalConsoleCount = (content.match(/console\.(log|info|warn|debug)\(/g) || []).length;
    
    if (originalConsoleCount === 0) return;
    
    // Wrap console.log with development check
    // Replace only console.log that are not already wrapped
    content = content.replace(
        /^(\s*)console\.(log|info|warn|debug)\(([\s\S]*?)\);$/gm,
        (match, indent, method, args) => {
            // Skip if already wrapped
            if (content.substring(Math.max(0, content.indexOf(match) - 100), content.indexOf(match)).includes('NODE_ENV')) {
                return match;
            }
            return `${indent}if (typeof process !== 'undefined' && process.env && process.env.NODE_ENV === 'development') {
${indent}    console.${method}(${args});
${indent}}`;
        }
    );
    
    const newConsoleCount = (content.match(/console\.(log|info|warn|debug)\(/g) || []).length;
    const fixed = originalConsoleCount - newConsoleCount;
    
    if (fixed > 0) {
        fs.writeFileSync(file, content);
        console.log(`  ✅ ${file.split('/').pop()}: Fixed ${fixed} console.${method} statements`);
        totalConsoleLogsFixed += fixed;
    }
});

console.log(`\n  📊 Total: Wrapped ${totalConsoleLogsFixed} console statements\n`);

